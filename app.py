if 'student_id' not in st.session_state: st.session_state.student_id = ''

st.sidebar.title('🧠 לומדת EMU')
mode = st.sidebar.radio('תצוגה', ['לומדה לסטודנט','מבחן מסכם','ניהול תוצאות'])

if mode == 'לומדה לסטודנט':
    st.title('לומדת EMU – ניטור וידאו־EEG')
    c1,c2 = st.columns(2)
    with c1: st.session_state.student_name = st.text_input('שם מלא', st.session_state.student_name)
    with c2: st.session_state.student_id = st.text_input('מספר מזהה / ת״ז', st.session_state.student_id)
    idx = st.sidebar.selectbox('פרק', range(len(chapters)), format_func=lambda i:f'{i+1}. {chapters[i][0]}', index=st.session_state.page)
    st.session_state.page = idx
    st.progress((idx+1)/len(chapters))
    st.markdown(chapters[idx][1], unsafe_allow_html=True)
    a,b = st.columns(2)
    with a:
        if idx>0 and st.button('→ הפרק הקודם', use_container_width=True): st.session_state.page-=1; st.rerun()
    with b:
        if idx<len(chapters)-1 and st.button('הפרק הבא ←', use_container_width=True): st.session_state.page+=1; st.rerun()
        elif idx==len(chapters)-1 and st.button('למבחן המסכם', use_container_width=True):
            st.session_state['go_exam']=True; st.info('בחרו “מבחן מסכם” בתפריט הצדדי.')

elif mode == 'מבחן מסכם':
    st.title('המבחן המסכם')
    st.write(f'20 שאלות. ציון מעבר: **{PASS_GRADE}%** (15 תשובות נכונות).')
    name = st.text_input('שם מלא', st.session_state.student_name, key='exam_name')
    sid = st.text_input('מספר מזהה / ת״ז', st.session_state.student_id, key='exam_id')
    st.caption('יש לבחור תשובה אחת לכל שאלה. התוצאה תישמר לאחר שליחת המבחן.')
    answers=[]
    with st.form('exam'):
        for i,(q,opts,correct) in enumerate(questions):
            ans=st.radio(f'{i+1}. {q}', ['— בחר/י תשובה —']+opts, key=f'q{i}')
            answers.append(ans)
        submitted=st.form_submit_button('הגש/י מבחן', use_container_width=True)
    if submitted:
        if not name.strip() or not sid.strip(): st.error('יש למלא שם ומספר מזהה.')
        elif any(a=='— בחר/י תשובה —' for a in answers): st.error('יש לענות על כל 20 השאלות.')
        else:
            correct_n=0
            for a,(_,opts,c) in zip(answers,questions):
                if a==opts[c]: correct_n+=1
            score=round(100*correct_n/len(questions))
            attempt=save_result(sid.strip(),name.strip(),score,correct_n,len(questions))
            if score>=PASS_GRADE: st.success(f'עברת את המבחן! ציון: {score}% ({correct_n}/20). ניסיון מספר {attempt}.')
            else: st.error(f'ציון: {score}% ({correct_n}/20). ציון המעבר הוא {PASS_GRADE}%. ניתן לעבור שוב על הלומדה ולנסות שנית.')

else:
    st.title('ניהול תוצאות')
    st.warning('בגרסת הפיתוח מסך זה אינו מוגן. לפני העלאה לשימוש אמיתי יש להוסיף אימות מנהל.')
    rows=get_results()
    if not rows: st.info('עדיין אין תוצאות.')
    else:
        import pandas as pd
        df=pd.DataFrame(rows,columns=['שם','מזהה','ציון','עבר','ניסיון','מועד'])
        df['עבר']=df['עבר'].map({1:'כן',0:'לא'})
        st.dataframe(df,use_container_width=True,hide_index=True)
        st.download_button('הורדת תוצאות כ־CSV',df.to_csv(index=False).encode('utf-8-sig'),'emu_results.csv','text/csv')
